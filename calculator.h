#pragma once

#include <string>

namespace calc {

// ============================================================================
//  calculator.h — 核心 API：对外的唯一接口
// ============================================================================
//  这是整个库"对外"的唯一入口。使用者只需要知道这一个函数。
//  所有的内部模块（Lexer、Parser、AST）都被封装在 .cpp 里，外部不可见。
//
//  设计原则：
//    1. 纯函数：同样的输入永远产生同样的输出，没有副作用（不修改全局状态）
//    2. 错误即异常：不合法的输入通过抛 runtime_error 报告，不用返回值区分成败
//    3. 零依赖：不依赖 I/O（不读文件、不打印），可嵌入任何项目
//
//  使用示例：
//    #include "calculator.h"
//    double result = calc::evaluate("2 + 3 * 4");  // → 14
//    double result = calc::evaluate("2^3");         // → 8
//
//  内部流程（使用者不需要关心，但了解一下有助于理解架构）：
//    字符串 → [Lexer] → Token 列表 → [Parser] → AST 树 → [evaluate] → 结果
//
//  支持的运算符（按优先级从低到高排列）：
//    +, -        加减（左结合：1-2-3 = (1-2)-3）
//    *, /        乘除（左结合：8/4/2 = (8/4)/2）
//    ^           乘方（右结合：2^3^2 = 2^(3^2) = 512）
//    -           一元负号（优先级高于 ^：-2^2 = -(2^2) = -4）
//    () [] {}    三种括号皆可分组，但必须同类型配对

[[nodiscard]] double evaluate(const std::string& expression);

} // namespace calc
